"""Deterministic offline adapter for demos and tests.

Behaviour per role:
* If the script file (AWF_SCRIPTED_RESPONSES) has an entry for the role whose `when` matches the
  task, its turns are replayed: each turn is a list of tool calls, or a `submit` payload.
* Otherwise an automatic behaviour derived from the contract is used: run the tools required by the
  completion rules, then submit template outputs that satisfy the contract's required sections.

Script format:

    roles:
      engineering.developer:
        - when: {iteration: 1}            # optional: iteration / attempt / title_contains
          turns:
            - tool_calls:
                - {name: fs.write, input: {path: src/x.py, content: "..."}}
            - tool_calls: [{name: test.run, input: {}}]
            - submit: {summary: "...", outputs: {implementation_summary: "..."}}
"""

from __future__ import annotations

import itertools
import json
import os
from pathlib import Path
from typing import Any

import yaml

from awf.agent_runtime.adapters.base import ModelAdapter, ModelSession, ModelTurn, ToolCall, ToolDef, ToolOutcome

SUBMIT_TOOL = "submit_result"
_ids = itertools.count(1)


def _model_name(name: str) -> str:
    return name.replace(".", "_")


def _fmt(value: Any, variables: dict[str, str]) -> Any:
    if isinstance(value, str):
        for key, val in variables.items():
            value = value.replace("{{" + key + "}}", val)
        return value
    if isinstance(value, dict):
        return {k: _fmt(v, variables) for k, v in value.items()}
    if isinstance(value, list):
        return [_fmt(v, variables) for v in value]
    return value


def template_output(output: dict[str, Any], meta: dict[str, Any]) -> Any:
    task = meta.get("task", {})
    title = task.get("title", "task")
    if output.get("type") == "json":
        schema = output.get("schema") or {}
        if "tasks" in (schema.get("properties") or {}):
            criteria = task.get("acceptance_criteria") or [f"{meta.get('objective', title)} is implemented and tested"]
            return {"tasks": [{
                "key": "T1",
                "title": (meta.get("objective") or title)[:200],
                "description": meta.get("objective") or title,
                "acceptance_criteria": criteria,
                "depends_on": [],
            }]}
        return {}
    heading = output.get("name", "output").replace("_", " ").title()
    lines = [f"# {heading}", "", f"Generated by `{meta.get('role')}` for: {title}", ""]
    for section in output.get("required_sections") or []:
        lines += [f"## {section}", "", f"{section} for {title}: no issues identified in automatic mode.", ""]
    if not output.get("required_sections"):
        lines += ["## Summary", "", f"Automatic {heading.lower()} for {title}.", ""]
    return "\n".join(lines)


class ScriptedSession(ModelSession):
    def __init__(self, turns: list[dict[str, Any]], meta: dict[str, Any], tools: list[ToolDef]):
        self.turns = turns
        self.meta = meta
        self.index = 0
        self.tool_names = {t.name for t in tools}

    def send(self, tool_outcomes: list[ToolOutcome] | None = None, user_text: str | None = None) -> ModelTurn:
        if user_text and self.index >= len(self.turns):
            # The runtime is nudging us after a rejected submit; re-submit the auto template.
            self.turns.append({"submit": {}})
        if self.index >= len(self.turns):
            self.turns.append({"submit": {}})
        turn = self.turns[self.index]
        self.index += 1
        calls: list[ToolCall] = []
        for call in turn.get("tool_calls") or []:
            name = _model_name(call["name"])
            if name in self.tool_names:
                calls.append(ToolCall(id=f"call_{next(_ids)}", name=name, input=dict(call.get("input") or {})))
        if "submit" in turn:
            calls.append(ToolCall(id=f"call_{next(_ids)}", name=SUBMIT_TOOL, input=self._submission(turn["submit"])))
        text = turn.get("text", "")
        return ModelTurn(text=text, tool_calls=calls, stop_reason="tool_use" if calls else "end_turn",
                         input_tokens=0, output_tokens=0, raw={"model": "scripted"})

    def _submission(self, scripted: dict[str, Any]) -> dict[str, Any]:
        contract = self.meta.get("contract", {})
        outputs = dict(scripted.get("outputs") or {})
        for out in contract.get("outputs", []):
            if out.get("produced_by", "agent") == "agent" and out.get("required", True) and out["name"] not in outputs:
                outputs[out["name"]] = template_output(out, self.meta)
        result: dict[str, Any] = {
            "summary": scripted.get("summary") or f"Automatic result for {self.meta.get('task', {}).get('title')}",
            "outputs": outputs,
        }
        if contract.get("decision"):
            values = contract["decision"].get("values") or ["APPROVE"]
            result["decision"] = scripted.get("decision", values[0])
            result["findings"] = scripted.get("findings", [])
        return result


class ScriptedAdapter(ModelAdapter):
    provider = "scripted"

    def __init__(self, script: dict[str, Any] | None = None, script_path: str | Path | None = None):
        if script is None:
            path = script_path or os.environ.get("AWF_SCRIPTED_RESPONSES")
            script = {}
            if path and Path(path).is_file():
                with open(path, encoding="utf-8") as fh:
                    script = yaml.safe_load(fh) or {}
        self.script = script

    def _match(self, role: str, meta: dict[str, Any]) -> list[dict[str, Any]] | None:
        task = meta.get("task", {})
        for entry in (self.script.get("roles") or {}).get(role, []):
            cond = entry.get("when") or {}
            if "iteration" in cond and cond["iteration"] != task.get("iteration"):
                continue
            if "attempt" in cond and cond["attempt"] != task.get("attempt"):
                continue
            if "title_contains" in cond and cond["title_contains"].lower() not in str(task.get("title", "")).lower():
                continue
            return [dict(t) for t in entry.get("turns", [])]
        return None

    def _auto_turns(self, meta: dict[str, Any]) -> list[dict[str, Any]]:
        contract = meta.get("contract", {})
        allowed = set(contract.get("allowed_tools") or [])
        calls = []
        rules = contract.get("completion_rules") or []
        for rule, tool in (("build_pass", "build.run"), ("unit_test_pass", "test.run"),
                           ("tests_executed", "test.run"), ("lint_pass", "lint.run")):
            if rule in rules and tool in allowed and {"name": tool, "input": {}} not in calls:
                calls.append({"name": tool, "input": {}})
        turns: list[dict[str, Any]] = []
        if "fs.list" in allowed:
            turns.append({"tool_calls": [{"name": "fs.list", "input": {"path": "."}}]})
        if calls:
            turns.append({"tool_calls": calls})
        turns.append({"submit": {}})
        return turns

    def start(self, *, system: str, user_message: str, tools: list[ToolDef], model: str,
              params: dict[str, Any], meta: dict[str, Any]) -> ModelSession:
        role = meta.get("role", "")
        turns = self._match(role, meta)
        if turns is None:
            turns = self._auto_turns(meta)
        task = meta.get("task", {})
        variables = {
            "task_title": str(task.get("title", "")),
            "objective": str(meta.get("objective", "")),
            "iteration": str(task.get("iteration", "")),
        }
        turns = _fmt(turns, variables)
        return ScriptedSession(json.loads(json.dumps(turns)), meta, tools)
