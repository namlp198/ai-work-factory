"""Canonical states and enumerations (Implementation Plan §5.5, Technical Design §11, §15)."""

from __future__ import annotations

from enum import StrEnum


class TaskState(StrEnum):
    NEW = "NEW"
    READY = "READY"
    RUNNING = "RUNNING"
    WAITING = "WAITING"
    REVIEW = "REVIEW"
    CHANGES_REQUIRED = "CHANGES_REQUIRED"
    APPROVAL_REQUIRED = "APPROVAL_REQUIRED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"
    DONE = "DONE"


TERMINAL_TASK_STATES = {TaskState.DONE, TaskState.CANCELLED, TaskState.FAILED}


class RunStatus(StrEnum):
    PENDING = "PENDING"
    RUNNING = "RUNNING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"


TERMINAL_RUN_STATUSES = {RunStatus.COMPLETED, RunStatus.FAILED, RunStatus.CANCELLED}


class ProjectStatus(StrEnum):
    ACTIVE = "ACTIVE"
    ARCHIVED = "ARCHIVED"


class JobState(StrEnum):
    QUEUED = "QUEUED"
    CLAIMED = "CLAIMED"
    PREPARING = "PREPARING"
    RUNNING = "RUNNING"
    UPLOADING_RESULT = "UPLOADING_RESULT"
    SUCCESS = "SUCCESS"
    FAILED = "FAILED"
    RETRYABLE = "RETRYABLE"
    TERMINAL = "TERMINAL"
    CANCELLED = "CANCELLED"


ACTIVE_JOB_STATES = {JobState.CLAIMED, JobState.PREPARING, JobState.RUNNING, JobState.UPLOADING_RESULT}


class JobType(StrEnum):
    AGENT = "agent"
    TOOL = "tool"


class AgentRunStatus(StrEnum):
    QUEUED = "QUEUED"
    RUNNING = "RUNNING"
    SUCCEEDED = "SUCCEEDED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"


class ApprovalState(StrEnum):
    PENDING = "PENDING"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    EXPIRED = "EXPIRED"


class WorkerStatus(StrEnum):
    ONLINE = "online"
    OFFLINE = "offline"
    DRAINING = "draining"
    REVOKED = "revoked"


class CriticDecision(StrEnum):
    PASS = "PASS"
    CHANGES_REQUIRED = "CHANGES_REQUIRED"
    BLOCK = "BLOCK"


class Severity(StrEnum):
    BLOCKER = "BLOCKER"
    MAJOR = "MAJOR"
    MINOR = "MINOR"
    INFO = "INFO"


class TaskType(StrEnum):
    AGENT = "agent"
    TOOL = "tool"
    GATE = "gate"


